def _inline(text: str) -> str:
    """Escape HTML, then apply a small set of inline markdown rules."""
    text = html.escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<em>\1</em>", text)
    text = re.sub(r"`(.+?)`", r"<code>\1</code>", text)
    text = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', text)
    return text


def _verdict_span(line: str) -> str:
    """Wrap a headline verdict line (e.g. '**ADVANCE — ...**') with a colored badge."""
    upper = line.upper()
    css_class = "verdict-advance" if "ADVANCE" in upper else "verdict-kill" if "KILL" in upper else None
    rendered = _inline(line)
    if css_class:
        return f'<p class="verdict-line {css_class}">{rendered}</p>'
    return f"<p>{rendered}</p>"


def markdown_to_html(markdown_text: str) -> str:
    """Minimal markdown -> HTML converter covering the memo generator's output
    surface: #/##/### headings, hr, bullet/numbered lists, paragraphs, and the
    inline styles handled by _inline(). Not a general-purpose parser."""
    lines = markdown_text.splitlines()
    html_parts: list[str] = []
    paragraph: list[str] = []
    list_buffer: list[str] = []
    list_tag: str | None = None
    first_heading_seen = False

    def flush_paragraph():
        nonlocal paragraph
        if paragraph:
            joined = " ".join(paragraph).strip()
            if joined.startswith("**") and joined.endswith("**") and joined.count("**") == 2:
                html_parts.append(_verdict_span(joined))
            else:
                html_parts.append(f"<p>{_inline(joined)}</p>")
            paragraph = []

    def flush_list():
        nonlocal list_buffer, list_tag
        if list_buffer:
            items = "".join(f"<li>{_inline(item)}</li>" for item in list_buffer)
            html_parts.append(f"<{list_tag}>{items}</{list_tag}>")
            list_buffer = []
            list_tag = None

    for raw_line in lines:
        line = raw_line.rstrip()
        stripped = line.strip()

        if not stripped:
            flush_paragraph()
            flush_list()
            continue

        if stripped == "---":
            flush_paragraph()
            flush_list()
            html_parts.append("<hr>")
            continue

        heading_match = re.match(r"^(#{1,3})\s+(.*)$", stripped)
        if heading_match:
            flush_paragraph()
            flush_list()
            level = len(heading_match.group(1))
            # First top-level heading is redundant with the masthead's company name.
            if level == 1 and not first_heading_seen:
                first_heading_seen = True
                continue
            tag = f"h{min(level + 1, 3)}" if level == 1 else f"h{level}"
            html_parts.append(f"<{tag}>{_inline(heading_match.group(2))}</{tag}>")
            continue

        bullet_match = re.match(r"^[-*]\s+(.*)$", stripped)
        numbered_match = re.match(r"^\d+\.\s+(.*)$", stripped)
        if bullet_match or numbered_match:
            flush_paragraph()
            tag = "ul" if bullet_match else "ol"
            if list_tag and list_tag != tag:
                flush_list()
            list_tag = tag
            list_buffer.append((bullet_match or numbered_match).group(1))
            continue

        flush_list()
        paragraph.append(stripped)

    flush_paragraph()
    flush_list()
    return "\n  ".join(html_parts)


def _company_name_from_slug(slug: str) -> str:
    """Capitalize each space-separated word without touching internal
    punctuation, so 'slang.ai' -> 'Slang.ai', not 'Slang.Ai'."""
    words = slug.replace("_", " ").split(" ")
    return " ".join(w[:1].upper() + w[1:] for w in words if w)


def render_memo(markdown_path: Path, output_path: Path | None = None) -> Path:
    markdown_text = markdown_path.read_text()
    company = _company_name_from_slug(markdown_path.stem.replace("_memo", ""))
    body_html = markdown_to_html(markdown_text)
    page = _PAGE_TEMPLATE.format(title=f"{company} — IC Memo", company=html.escape(company), body=body_html)

    output_path = output_path or markdown_path.with_suffix(".html")
    output_path.write_text(page)
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Render an IC memo markdown file to standalone HTML.")
    parser.add_argument("memo", nargs="*", help="Path(s) to memo markdown file(s). Defaults to all *_memo.md in data/memos/.")
    args = parser.parse_args()

    paths = [Path(p) for p in args.memo] if args.memo else sorted(config.MEMO_DIR.glob("*_memo.md"))
    if not paths:
        print(f"No memo files found in {config.MEMO_DIR}.")
        return

    for path in paths:
        output = render_memo(path)
        print(f"{path} -> {output}")


if __name__ == "__main__":
    main()
