"""
Milestone 3 — Phase evaluation suite.

Loads the Phase 1 fixture batch saved under evals/fixtures/ (generated by
running the live agent — see PROGRESS.md session log for how/when) and checks:

  1. Verdict direction — the 4 non-boundary companies must land on the
     expected side (advance/kill).
  2. Abridge boundary case — NOT asserted to a single verdict. Instead we
     report the distribution across 5 real runs, honestly, so instability
     is visible rather than assumed away.
  3. Cost regression guard — every run stays under a sane per-run ceiling.
  4. Tool-selection sanity — GitHub is skipped for closed-vertical
     enterprise companies (the "closed source = skip" rule from
     orchestrator/prompts.py), and every run has a non-empty rationale.

This does NOT call any API — it's pure fixture validation. To regenerate the
fixtures (real, billed API calls against arXiv/Tavily/GitHub + Claude),
re-run the Phase 1 agent against each company and overwrite evals/fixtures/.

Run directly: `python3 evals/phase_evals.py`. Exits non-zero on any assertion
failure (the directional/cost/tool checks — NOT the Abridge distribution,
which has no pass/fail by design).
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

FIXTURES_DIR = Path(__file__).parent / "fixtures"
MAX_COST_PER_RUN = 0.10
VALID_VERDICTS = {"advance", "kill", "needs-more-info"}

# The 4 non-boundary fixtures + expected verdict direction.
DIRECTIONAL_EXPECTATIONS = {
    "slangai.json": "advance",   # vertical (restaurants) + full phone-answering automation, no human review
    "chatbase.json": "kill",     # horizontal GPT wrapper, no vertical moat
    "glean.json": "kill",        # horizontal enterprise search/assistant, explicit augmentation framing
    "rogo.json": "advance",      # vertical (investment banking) + explicit junior-analyst replacement framing
}

# All fixture companies in this batch are closed-source enterprise SaaS —
# none should have burned a search slot on github_search. (We don't yet have
# a fixture for the "should call github_search" side of the rule — e.g. an
# open-source-adjacent dev-tool company — that's a real gap, noted below.)
EXPECT_GITHUB_SKIPPED = {
    "slangai.json", "chatbase.json", "glean.json", "rogo.json",
    "abridge_run1.json", "abridge_run2.json", "abridge_run3.json",
    "abridge_run4.json", "abridge_run5.json", "evenup.json",
}

ABRIDGE_FILES = [f"abridge_run{i}.json" for i in range(1, 6)]


def _load(name: str) -> dict:
    return json.loads((FIXTURES_DIR / name).read_text())


def _cost(fixture: dict) -> float:
    return fixture.get("cost_usd", 0.0)


def run() -> bool:
    all_files = sorted(p.name for p in FIXTURES_DIR.glob("*.json"))
    if not all_files:
        print(f"No fixtures found in {FIXTURES_DIR}. Nothing to eval.")
        return False

    print("=" * 70)
    print("PHASE 1 EVALS")
    print("=" * 70)

    ok = True

    # --- 1. Basic well-formedness + cost guard, every fixture ---------------
    print(f"\n[well-formedness + cost] ceiling ${MAX_COST_PER_RUN:.2f}/run")
    for name in all_files:
        f = _load(name)
        failures = []
        if f.get("verdict") not in VALID_VERDICTS:
            failures.append(f"invalid verdict {f.get('verdict')!r}")
        if not f.get("rationale", "").strip():
            failures.append("empty rationale")
        if not (0.0 <= f.get("confidence", -1) <= 1.0):
            failures.append(f"confidence {f.get('confidence')} out of range")
        cost = _cost(f)
        if cost > MAX_COST_PER_RUN:
            failures.append(f"cost ${cost:.4f} exceeds ${MAX_COST_PER_RUN:.2f}/run ceiling")
        status = "PASS" if not failures else "FAIL"
        print(f"  {status}  {name}  (${cost:.4f})")
        for reason in failures:
            print(f"        - {reason}")
        ok = ok and not failures

    # --- 2. Tool-selection sanity: GitHub skipped for closed-vertical -------
    print("\n[tool selection] github_search should be skipped for closed-vertical companies")
    for name in sorted(EXPECT_GITHUB_SKIPPED):
        if name not in all_files:
            continue
        f = _load(name)
        called_github = "github_search" in f.get("tools_used", [])
        status = "PASS" if not called_github else "FAIL"
        print(f"  {status}  {name}  tools_used={f.get('tools_used')}")
        ok = ok and not called_github
    print("  NOTE: no fixture in this batch tests the opposite case (github_search")
    print("        correctly INCLUDED for an open-source-adjacent company) — gap, not covered yet.")

    # --- 3. Verdict direction, the 4 non-boundary companies ------------------
    print("\n[verdict direction] non-boundary companies")
    for name, expected in DIRECTIONAL_EXPECTATIONS.items():
        if name not in all_files:
            print(f"  MISSING  {name} (expected {expected}) — fixture not found")
            ok = False
            continue
        f = _load(name)
        actual = f.get("verdict")
        passed = actual == expected
        status = "PASS" if passed else "FAIL"
        print(f"  {status}  {f['company']:<12} expected={expected:<7} actual={actual:<16} "
              f"confidence={f.get('confidence'):.2f}")
        ok = ok and passed

    # --- 4. Abridge boundary case: report distribution, do not assert -------
    print("\n[Abridge boundary case] 5-run distribution — NOT asserted to a single verdict")
    abridge_fixtures = [_load(n) for n in ABRIDGE_FILES if n in all_files]
    if len(abridge_fixtures) < 5:
        print(f"  WARNING: expected 5 Abridge runs, found {len(abridge_fixtures)}")
    counts = Counter(f["verdict"] for f in abridge_fixtures)
    n = len(abridge_fixtures)
    for verdict, count in counts.most_common():
        confidences = [f["confidence"] for f in abridge_fixtures if f["verdict"] == verdict]
        conf_str = ", ".join(f"{c:.2f}" for c in confidences)
        print(f"  {verdict}: {count}/{n}  (confidence: {conf_str})")
    if len(counts) > 1:
        print("  -> UNSTABLE: verdict is not deterministic across identical runs. This is the")
        print("     known miscalibration issue tracked in PROGRESS.md, not a new regression.")
    else:
        print("  -> STABLE across all 5 runs.")

    print("\n" + "=" * 70)
    print("OVERALL (excluding Abridge distribution, which has no pass/fail): "
          + ("PASS" if ok else "FAIL"))
    print("=" * 70)
    return ok


if __name__ == "__main__":
    sys.exit(0 if run() else 1)
